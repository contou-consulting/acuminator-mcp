"""Analyze a raw C# snippet by planting it inside a reference Acumatica project.

Acuminator needs the full Acumatica Framework type environment to do semantic
analysis (``PXGraph``, ``PXSelect``, DAC attributes etc). Since the Acumatica
Framework isn't on public NuGet, the snippet is dropped into an existing
Acumatica `.csproj` (the "reference project") whose references already resolve
the framework types.

Resolution order for the reference project:

  1. Explicit ``reference_project_path`` argument.
  2. ``ACUMINATOR_MCP_REFERENCE_PROJECT`` environment variable.
  3. Auto-discover by scanning the server's current working directory:
     walk up looking for any ``*.csproj``, then BFS down (skipping noise
     dirs like ``bin``/``obj``/``packages``).

Flow:
  1. Drop a temp ``.cs`` file at the root of the reference project's directory.
  2. Run the Acuminator runner against that project.
  3. Keep only the diagnostics that target the temp file.
  4. Delete the temp file (even on error).

This is invasive on the reference project dir but non-destructive: we only
add one file, then remove it. Users may want to add ``AcuminatorMcpSnippet_*.cs``
to their ``.gitignore`` to protect against orphan files if the server crashes
mid-analysis.
"""

from __future__ import annotations

import contextlib
import os
import tempfile
import uuid
from collections import deque
from pathlib import Path

from acuminator_mcp import runner
from acuminator_mcp.config import reference_project_path
from acuminator_mcp.report import AnalysisResult, Diagnostic, parse_report_file


class SnippetError(RuntimeError):
    """Raised when a snippet cannot be analyzed (e.g. no reference project found)."""


_SNIPPET_WRAPPER_HEADER = "// Auto-generated by acuminator-mcp. Do not edit.\n"
_IGNORED_DIRS = frozenset(
    {
        "bin",
        "obj",
        "packages",
        "node_modules",
        "TestResults",
        "dist",
        "build",
    }
)
_MAX_DISCOVERY_DEPTH = 4


def _project_dir(project_path: Path) -> Path:
    if project_path.is_dir():
        return project_path
    return project_path.parent


def _first_csproj_in_dir(dir_path: Path) -> Path | None:
    try:
        for child in sorted(dir_path.iterdir()):
            if child.is_file() and child.suffix.lower() == ".csproj":
                return child
    except OSError:
        return None
    return None


def _walk_up_for_csproj(start: Path) -> Path | None:
    current = start.resolve()
    while True:
        match = _first_csproj_in_dir(current)
        if match is not None:
            return match
        parent = current.parent
        if parent == current:
            return None
        current = parent


def _scan_down_for_csproj(start: Path, max_depth: int = _MAX_DISCOVERY_DEPTH) -> Path | None:
    start = start.resolve()
    queue: deque[tuple[Path, int]] = deque([(start, 0)])
    visited: set[Path] = set()
    while queue:
        current, depth = queue.popleft()
        if current in visited:
            continue
        visited.add(current)
        match = _first_csproj_in_dir(current)
        if match is not None:
            return match
        if depth >= max_depth:
            continue
        try:
            children = list(current.iterdir())
        except OSError:
            continue
        for child in children:
            if not child.is_dir():
                continue
            if child.name.startswith(".") or child.name.lower() in _IGNORED_DIRS:
                continue
            queue.append((child, depth + 1))
    return None


def discover_reference_project(start: Path | None = None) -> Path | None:
    """Best-effort search for a ``.csproj`` near the given starting directory.

    Walks up from ``start`` first, then BFS-scans down. Returns ``None`` if
    no ``.csproj`` is found anywhere reachable within the depth limit.
    """
    start = start or Path.cwd()
    up = _walk_up_for_csproj(start)
    if up is not None:
        return up
    return _scan_down_for_csproj(start)


def _resolve_reference(override: str | None) -> Path:
    if override:
        target: Path | None = Path(override)
    else:
        target = reference_project_path() or discover_reference_project()

    if target is None:
        raise SnippetError(
            "No reference project found. Tried (1) reference_project_path argument, "
            "(2) ACUMINATOR_MCP_REFERENCE_PROJECT env var, and (3) auto-discovery from "
            f"the server's CWD ({Path.cwd()}). Point the tool at an Acumatica .csproj "
            "whose references resolve the Acumatica Framework."
        )
    if not target.exists():
        raise SnippetError(f"Reference project does not exist: {target}")
    return target


def _wrap_snippet(code: str) -> str:
    stripped = code.lstrip()
    if stripped.startswith("using ") or stripped.startswith("namespace "):
        return _SNIPPET_WRAPPER_HEADER + code
    wrapped = (
        "using PX.Data;\n"
        "using PX.Objects;\n"
        "\n"
        "namespace AcuminatorMcp.Snippet\n"
        "{\n"
        f"{code}\n"
        "}\n"
    )
    return _SNIPPET_WRAPPER_HEADER + wrapped


async def analyze_snippet(
    code: str,
    *,
    reference_project_path: str | None = None,
    isv_mode: bool = False,
) -> AnalysisResult:
    """Analyze a C# snippet against a reference Acumatica project.

    Returns an :class:`AnalysisResult` containing only the diagnostics that
    Acuminator reported against the planted snippet file.
    """
    ref_project = _resolve_reference(reference_project_path)
    project_dir = _project_dir(ref_project)

    snippet_name = f"AcuminatorMcpSnippet_{uuid.uuid4().hex[:12]}.cs"
    snippet_path = project_dir / snippet_name
    snippet_path.write_text(_wrap_snippet(code), encoding="utf-8")

    try:
        with tempfile.TemporaryDirectory(prefix="acuminator-mcp-") as tmp:
            report_path = Path(tmp) / "report.json"
            _, stderr = await runner.run_analysis(
                ref_project,
                output_json=report_path,
                isv_mode=isv_mode,
            )
            if not report_path.exists():
                raise SnippetError(
                    "Acuminator runner did not produce a JSON report for the snippet. "
                    f"Runner output:\n{stderr}"
                )
            full = parse_report_file(report_path)
    finally:
        with contextlib.suppress(OSError):
            snippet_path.unlink(missing_ok=True)

    snippet_abs = str(snippet_path.resolve())
    snippet_name_lower = snippet_name.lower()

    def _targets_snippet(d: Diagnostic) -> bool:
        if not d.file:
            return False
        f = d.file.replace("\\", "/").lower()
        if f.endswith(snippet_name_lower):
            return True
        return os.path.normcase(d.file) == os.path.normcase(snippet_abs)

    snippet_diagnostics = [d for d in full.diagnostics if _targets_snippet(d)]
    return AnalysisResult(
        code_source=f"snippet://{snippet_name} (ref: {ref_project})",
        total_diagnostics=len(snippet_diagnostics),
        diagnostics=snippet_diagnostics,
    )
