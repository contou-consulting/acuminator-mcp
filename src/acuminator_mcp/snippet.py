"""Analyze a raw C# snippet by planting it inside a reference Acumatica project.

Acuminator needs the full Acumatica Framework type environment to do semantic
analysis (e.g. recognizing ``PXGraph``, ``PXSelect``, DAC attributes). Since the
Acumatica Framework is not published on public NuGet, we require the caller to
point us at an existing Acumatica project (or solution) whose ``References``
already resolve the framework types.

Flow:
  1. Drop a temp ``.cs`` file at the root of the reference project's directory.
  2. Run the Acuminator runner against that project.
  3. Keep only the diagnostics that target the temp file.
  4. Delete the temp file (even on error).

This is invasive on the reference project dir but non-destructive: we only add
one file, then remove it. Callers should supply a reference project they're
willing to let us touch (a "scratch" project is ideal).
"""

from __future__ import annotations

import contextlib
import os
import tempfile
import uuid
from pathlib import Path

from acuminator_mcp import runner
from acuminator_mcp.config import reference_project_path
from acuminator_mcp.report import AnalysisResult, Diagnostic, parse_report_file


class SnippetError(RuntimeError):
    """Raised when a snippet cannot be analyzed (e.g. missing reference project)."""


_SNIPPET_WRAPPER_HEADER = "// Auto-generated by acuminator-mcp. Do not edit.\n"


def _project_dir(project_path: Path) -> Path:
    if project_path.is_dir():
        return project_path
    return project_path.parent


def _resolve_reference(override: str | None) -> Path:
    target = Path(override) if override else reference_project_path()
    if target is None:
        raise SnippetError(
            "No reference project configured. Set ACUMINATOR_MCP_REFERENCE_PROJECT "
            "or pass reference_project_path to the tool. It must point at an "
            "Acumatica .csproj whose references resolve the Acumatica Framework."
        )
    if not target.exists():
        raise SnippetError(f"Reference project does not exist: {target}")
    return target


def _wrap_snippet(code: str) -> str:
    stripped = code.lstrip()
    if stripped.startswith("using ") or stripped.startswith("namespace "):
        return _SNIPPET_WRAPPER_HEADER + code
    wrapped = (
        "using PX.Data;\n"
        "using PX.Objects;\n"
        "\n"
        "namespace AcuminatorMcp.Snippet\n"
        "{\n"
        f"{code}\n"
        "}\n"
    )
    return _SNIPPET_WRAPPER_HEADER + wrapped


async def analyze_snippet(
    code: str,
    *,
    reference_project_path: str | None = None,
    isv_mode: bool = False,
) -> AnalysisResult:
    """Analyze a C# snippet against the configured reference project.

    Returns an :class:`AnalysisResult` containing only the diagnostics that Acuminator
    reported against the planted snippet file.
    """
    ref_project = _resolve_reference(reference_project_path)
    project_dir = _project_dir(ref_project)

    snippet_name = f"AcuminatorMcpSnippet_{uuid.uuid4().hex[:12]}.cs"
    snippet_path = project_dir / snippet_name
    snippet_path.write_text(_wrap_snippet(code), encoding="utf-8")

    try:
        with tempfile.TemporaryDirectory(prefix="acuminator-mcp-") as tmp:
            report_path = Path(tmp) / "report.json"
            _, stderr = await runner.run_analysis(
                ref_project,
                output_json=report_path,
                isv_mode=isv_mode,
            )
            if not report_path.exists():
                raise SnippetError(
                    "Acuminator runner did not produce a JSON report for the snippet. "
                    f"Runner output:\n{stderr}"
                )
            full = parse_report_file(report_path)
    finally:
        with contextlib.suppress(OSError):
            snippet_path.unlink(missing_ok=True)

    snippet_abs = str(snippet_path.resolve())
    snippet_name_lower = snippet_name.lower()

    def _targets_snippet(d: Diagnostic) -> bool:
        if not d.file:
            return False
        f = d.file.replace("\\", "/").lower()
        if f.endswith(snippet_name_lower):
            return True
        return os.path.normcase(d.file) == os.path.normcase(snippet_abs)

    snippet_diagnostics = [d for d in full.diagnostics if _targets_snippet(d)]
    return AnalysisResult(
        code_source=f"snippet://{snippet_name}",
        total_diagnostics=len(snippet_diagnostics),
        diagnostics=snippet_diagnostics,
    )
